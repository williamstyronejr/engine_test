#!/usr/bin/env python3
"""Regenerate protocol/Unicode data; not needed to build or run the engine."""
import argparse
import hashlib
from pathlib import Path
import re
import unicodedata


def generate(header):
    if unicodedata.unidata_version != "16.0.0":
        raise RuntimeError("Regeneration requires Python with Unicode 16.0.0 data")
    source = header.read_bytes()
    aliases = {}
    # Only exact character mappings, excluding parenthesized approximations,
    # function/keypad symbols and directly encoded Latin-1/Unicode symbols.
    for raw, unicode in re.findall(
        rb"#define\s+XK_\w+\s+0x([0-9a-fA-F]+)\s+/\* U\+([0-9A-F]+)", source
    ):
        symbol, point = int(raw, 16), int(unicode, 16)
        if 0x100 <= symbol <= 0x20FF:
            if symbol in aliases and aliases[symbol] != point:
                raise RuntimeError("Conflicting legacy character mapping")
            aliases[symbol] = point
    if len(aliases) < 500:
        raise RuntimeError("Incomplete X11 keysym header")
    ranges = []
    for point in range(0xA1, 0x110000):
        if unicodedata.category(chr(point))[0] not in "LNPS":
            continue
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    lines = [
        "// Generated by tools/make_keyboard_data.py; do not edit.",
        "// Protocol/Unicode data notices: docs/KEYBOARD_DATA.md.",
        f"// keysymdef.h SHA256: {hashlib.sha256(source).hexdigest()}",
        "// Unicode 16.0.0 categories: Letter, Number, Punctuation, Symbol.",
        "constexpr CharacterAlias character_aliases[]{",
    ]
    lines += [f"    {{0x{symbol:x}, 0x{point:x}}}," for symbol, point in sorted(aliases.items())]
    lines += ["};", "constexpr CharacterRange character_ranges[]{"]
    lines += [f"    {{0x{first:x}, 0x{last:x}}}," for first, last in ranges]
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keysym-header", type=Path, default=Path("/usr/include/X11/keysymdef.h"))
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "engine/src/keyboard_data.inc")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.keysym_header)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("Keyboard data differs; regenerate and review the change")
    else:
        args.output.write_text(result)


if __name__ == "__main__":
    main()
